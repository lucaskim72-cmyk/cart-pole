import cv2
import numpy as np
import gymnasium as gym

# 다시 환경을 초기화하고, 충돌이 시각화되는 프레임을 얻기 위한 시뮬레이션을 진행합니다.
base_env = gym.make("CartPole-v1", render_mode="rgb_array")
env_disturbed = DisturbedCartPoleEnv(base_env)

observation, info = env_disturbed.reset()
frames_visual_collision = []
steps = 200
epsilon = 0.3

# 충돌 시각 효과 정보를 담을 변수
active_effects = []

def get_best_action(obs):
    pole_angle = obs[2]
    return 1 if pole_angle < 0 else 0

print("=== 실제 충돌체가 표시되는 애니메이션 프레임 수집 시작 ===")

for step in range(steps):
    # 1. 원본 화면 프레임 가져오기 (복사본을 생성해 위에 픽셀을 덧그립니다)
    frame = env_disturbed.render().copy()

    # 2. 카트의 현재 화면상 위치 역추적 (카트폴 화면 좌표는 대략 중앙 하단 부근)
    # 환경 관측치 observation[0]은 카트의 물리적 X 위치 (-2.4 ~ 2.4 범위)
    cart_x_phys = observation[0]
    # 화면 해상도는 보통 (400, 600, 3) 또는 (500, 600, 3) 정도입니다.
    h, w, c = frame.shape
    # 물리적 위치를 화면 가로 픽셀 좌표(0 ~ w)로 선형 변환
    cart_x_pixel = int((cart_x_phys / 4.8 + 0.5) * w)
    cart_y_pixel = int(h * 0.72) # 대략 카트 본체가 위치한 Y축 높이

    # Epsilon-Greedy 행동 결정 및 한 단계 전진
    random_value = np.random.rand()
    if random_value < epsilon:
        action = env_disturbed.action_space.sample()
    else:
        action = get_best_action(observation)

    # step을 진행하기 전에 충돌 여부를 감지하기 위해 임시로 시뮬레이션의 step을 직접 래핑한 속성을 관찰할 수도 있으나,
    # 기존의 DisturbedCartPoleEnv 내부 step을 실행하여 화면 갱신을 확인합니다.
    # 여기서는 무작위 확률(8%) 충돌 상황을 렌더링 프레임 단위와 동기화하여 시각화 효과를 적용합니다.

    # env_disturbed.step 내부에서 무작위 확률로 수정한 물리값을 가로채기 위해 수동으로도 그릴 수 있도록 환경 래퍼의 동작과 맞춥니다.
    # 이미 이전 step 실행 중 충돌 이벤트가 로그로 찍혔으므로, 충돌 순간에 맞추어 시각효과(active_effects)를 추가합니다.
    collision_occurred = np.random.rand() < 0.08

    if collision_occurred:
        impact_level = np.random.choice(["약", "중", "강"])
        direction = np.random.choice([-1, 1])

        # 충돌 효과 정보 저장 (충돌 지점, 강도, 진행 시간 카운트다운)
        active_effects.append({
            "pos": (cart_x_pixel, cart_y_pixel),
            "level": impact_level,
            "dir": direction,
            "life": 6 # 6프레임 동안 화면에 잔상과 충돌 구체를 유지시킵니다.
        })

        # 물리 상태 강제 수정 (실제 환경에도 동기화)
        force = env_disturbed.impact_forces[impact_level]
        state = list(env_disturbed.env.unwrapped.state)
        state[1] += force * direction
        state[3] += force * direction * 1.5
        env_disturbed.env.unwrapped.state = tuple(state)
        observation = np.array(env_disturbed.env.unwrapped.state, dtype=np.float32)

        direction_str = "오른쪽" if direction > 0 else "왼쪽"
        print(f"💥 [시각화 추가] 스텝 {step+1}: {direction_str}에서 [{impact_level}] 충격체가 충돌했습니다!")

    # 3. 누적된 액티브 충돌 효과를 프레임 이미지 위에 덧그리기
    for effect in list(active_effects):
        cx, cy = effect["pos"]
        level = effect["level"]
        direction = effect["dir"]

        # 충격 레벨별 색상 및 크기 지정
        color_map = {"약": (0, 200, 255), "중": (0, 120, 255), "강": (255, 0, 0)} # RGB
        radius_map = {"약": 12, "중": 18, "강": 26}

        color = color_map[level]
        radius = radius_map[level]

        # 충격체(빨간색/노란색 계열의 원)가 날아오는 시작 지점 계산
        # 충돌 잔상 애니메이션 연출
        offset_x = direction * (effect["life"] * 15)
        bullet_x = cx - offset_x
        bullet_y = cy - 5

        # 충돌체(구체) 그리기
        if 0 <= bullet_x < w:
            cv2.circle(frame, (int(bullet_x), int(bullet_y)), radius, color, -1) # 꽉 찬 원
            cv2.circle(frame, (int(bullet_x), int(bullet_y)), radius + 4, (255, 255, 255), 2) # 테두리

        # 충격 방향 화살표 그리기
        arrow_start = (int(cx - direction * 60), int(cy - 5))
        arrow_end = (int(cx - direction * 15), int(cy - 5))
        cv2.arrowedLine(frame, arrow_start, arrow_end, (255, 50, 50), 3, tipLength=0.3)

        # 충격 텍스트 표시
        cv2.putText(frame, f"CRASH ({level})!", (int(cx - 50), int(cy - 50)),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 0, 0), 2, cv2.LINE_AA)

        effect["life"] -= 1
        if effect["life"] <= 0:
            active_effects.remove(effect)

    # 최종 가공된 프레임 저장
    frames_visual_collision.append(frame)

    # 환경 한 스텝 이동
    observation, reward, terminated, truncated, info = env_disturbed.step(action)

    if terminated or truncated:
        observation, info = env_disturbed.reset()

env_disturbed.close()

