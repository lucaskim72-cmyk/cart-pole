import gymnasium as gym
import numpy as np

class DisturbedCartPoleEnv(gym.Wrapper):
    def __init__(self, env):
        super().__init__(env)
        # 충돌 강도 정의: 약(Weak), 중(Medium), 강(Strong)
        self.impact_forces = {
            "약": 0.5,
            "중": 1.5,
            "강": 3.0
        }

    def step(self, action):
        # 1. 기본 카트폴의 물리 법칙에 따라 한 스텝 진행
        observation, reward, terminated, truncated, info = self.env.step(action)

        # 2. 8%의 무작위 확률로 충돌 발생
        collision_occurred = np.random.rand() < 0.08

        if collision_occurred:
            # 강, 중, 약 3가지 중 하나를 랜덤하게 선택
            impact_level = np.random.choice(["약", "중", "강"])
            force = self.impact_forces[impact_level]

            # 왼쪽(-1) 혹은 오른쪽(+1) 무작위 충격 방향 결정
            direction = np.random.choice([-1, 1])
            actual_force = force * direction

            # 카트폴의 내부 물리 상태(state) 강제 수정
            # state 구조: [카트 위치, 카트 속도, 막대 각도, 막대 각속도]
            state = list(self.env.unwrapped.state)

            # 카트 속도와 막대 각속도에 즉각적인 외부 충격(속도 변화) 반영
            state[1] += actual_force        # 카트 속도에 충격 가함
            state[3] += actual_force * 1.5  # 막대 회전 속도에도 충격 가함

            self.env.unwrapped.state = tuple(state)

            # 수정된 물리 상태를 반영하여 새로운 관측값(observation) 갱신
            observation = np.array(self.env.unwrapped.state, dtype=np.float32)

            # 사용자 편의를 위해 로그 기록
            direction_str = "오른쪽" if direction > 0 else "왼쪽"
            print(f"💥 충돌 발생! 옆 카트가 [{direction_str}]에서 [{impact_level}] 수준(힘: {force})으로 들이받았습니다!")

        return observation, reward, terminated, truncated, info

