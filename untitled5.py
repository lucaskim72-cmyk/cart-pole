import numpy as np
import gymnasium as gym

env = gym.make("CartPole-v1")

# 입실론 설정 (0.3 = 30% 확률로 탐험, 70% 확률로 최선의 선택)
epsilon = 0.3

# 간단히 작동 방식을 보기 위해, 가상의 '학습된 가치'(Q-table 형태)가 있다고 가정해 봅시다.
# 실제로는 이 테이블을 신경망이나 표를 통해 학습하게 됩니다.
# 여기서는 막대 각도가 왼쪽으로 기울어지면 오른쪽으로 밀고, 오른쪽으로 기울어지면 왼쪽으로 미는 것이 유리하다는 간단한 규칙(Heuristic)을 이용(Exploitation) 행동으로 설정하겠습니다.
def get_best_action(observation):
    pole_angle = observation[2]
    # 막대가 왼쪽으로 기울어지면(각도 < 0) -> 오른쪽(1)으로 밀고,
    # 오른쪽으로 기울어지면(각도 >= 0) -> 왼쪽(0)으로 미는 것이 유리하다고 판단
    return 1 if pole_angle < 0 else 0

observation, info = env.reset()

print(f"[시작] 설정된 Epsilon (탐험 확률): {epsilon * 100}%\n")

for step in range(10):
    # 0과 1 사이의 무작위 난수 생성
    random_value = np.random.rand()

    if random_value < epsilon:
        # 1. 탐험 (Exploration) 실행
        action = env.action_space.sample()
        action_type = "★ Exploration (탐험 - 무작위 행동)"
    else:
        # 2. 이용 (Exploitation) 실행
        action = get_best_action(observation)
        action_type = "● Exploitation (이용 - 판단된 최선책)"

    observation, reward, terminated, truncated, info = env.step(action)

    print(f"Step {step+1}: {action_type} -> 선택된 행동: {action}")
    print(f"      상태(막대 각도): {observation[2]:.4f}, 보상: {reward}\n")

    if terminated or truncated:
        observation, info = env.reset()

env.close()

